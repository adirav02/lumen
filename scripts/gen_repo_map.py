# TL;DR: Generate a compact repository tree and module purposes from local source metadata.
# Status: active; date: 2026-10-19.
"""Static AST/README inspection only; never import application modules."""
import argparse
import ast
from pathlib import Path
from _devtools import ROOT, header, write_generated

EXCLUDE = {'.git', '.venv', '.lumen', '.pytest_cache', '__pycache__', 'build',
           'dist', 'scratch', 'node_modules', '_archive', '.tmp', 'test-results'}


def purpose(path):
    source = path / '__init__.py' if path.is_dir() else path
    if source.suffix == '.py' and source.is_file():
        try:
            doc = ast.get_docstring(ast.parse(source.read_text()))
            if doc:
                return doc.strip().splitlines()[0]
        except (SyntaxError, UnicodeError):
            pass
    for name in ('README.md', 'README'):
        readme = path / name if path.is_dir() else path.parent / name
        if readme.is_file():
            for line in readme.read_text().splitlines():
                if line.strip() and not line.startswith(('#', 'Status:', '---', '```')):
                    return line.removeprefix('TL;DR:').strip()[:160]
    return 'No module docstring or README purpose available.'


def generate(root, check=False):
    text = header('Repository directories and module purposes from AST/README metadata.',
                  'GENERATED by scripts/gen_repo_map.py')
    lines = [text.rstrip(), '', '# Repository map', '', '```text', './']
    for path in sorted(root.iterdir()):
        if path.name in EXCLUDE or path.name.endswith(('.egg-info', '.sync', '.db', '.pdf')):
            continue
        if path.is_dir():
            lines.append(f'  {path.name}/')
            for child in sorted(path.iterdir()):
                if child.is_dir() and child.name not in EXCLUDE and not child.name.endswith('.egg-info'):
                    if path.name == 'work' and child.name != '_template':
                        continue
                    lines.append(f'    {child.name}/')
        elif path.name in {'AGENTS.md', 'CLAUDE.md', 'README.md', 'goal.md', 'plan.md', 'pyproject.toml'}:
            lines.append(f'  {path.name}')
    lines += ['```', '', '## Top-level Python modules', '', '| Module | Purpose |', '|---|---|']
    source = root / 'src'
    for package in sorted(source.iterdir()) if source.exists() else []:
        if not package.is_dir() or package.name.endswith('.egg-info'):
            continue
        for module in [package] + sorted(package.iterdir()):
            if module.name.startswith('_') or (module.is_file() and module.suffix != '.py'):
                continue
            summary = purpose(module).replace('|', '/')
            lines.append(f'| `{module.relative_to(root)}` | {summary} |')
    result = '\n'.join(lines) + '\n'
    if len(result.splitlines()) > 150:
        raise ValueError('Map exceeds 150 lines; reduce tree depth before generating')
    return write_generated(root / 'docs/repo-map.md', result, check)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raise SystemExit(0 if generate(args.root.resolve(), args.check) else 1)
